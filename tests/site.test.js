const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'assets/js/site.js'),'utf8');
const css=fs.readFileSync(path.join(root,'assets/css/styles.css'),'utf8');
const cfg=fs.readFileSync(path.join(root,'assets/js/config.js'),'utf8');
assert.ok(html.includes('7<span>%</span>'), 'Bronze 7% tier missing');
assert.ok(html.includes('70<span>%</span>'), 'Angel 70% tier missing');
assert.ok(html.includes('whitepaper/Gambit_Whitepaper_v2_2.pdf'), 'Final whitepaper missing in page');
assert.ok(fs.existsSync(path.join(root,'whitepaper/Gambit_Whitepaper_v2_2.pdf')));
assert.ok(html.includes('100,000,000,000,000'), 'Token supply missing');
assert.ok(html.includes('$0.0001'), 'Price missing');
assert.ok(!html.includes('PROJECT CONCEPT / TESTNET DEVELOPMENT'));
assert.ok(!html.includes('IN DEVELOPMENT'));
assert.ok(html.includes('id="wallet-cap-hero"') && html.includes('id="launch-countdown-wrap"'));
assert.ok(js.includes('Math.max(0,profit)*tier.rate'), 'Reward must be positive-only');
assert.ok(js.includes("byId('launch-countdown-wrap').hidden=false"));
assert.ok(cfg.includes("presaleUsdPrice: 0.0001") && cfg.includes('walletCapUsd: 1000'));
assert.ok(css.includes('@media(max-width:650px)'), 'Missing mobile styles');
assert.ok(!js.includes('eth_sendTransaction'), 'UI logic must never send wallet transactions');
console.log('14 Gambit site checks passed');
