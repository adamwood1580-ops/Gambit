const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname, '..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'assets/js/exchange.js'),'utf8');
const config=fs.readFileSync(path.join(root,'assets/js/config.js'),'utf8');
const check=(ok,msg)=>assert.ok(ok,msg);
check(html.includes('id="exchange"'), 'Wallet desk missing');
check(html.includes('id="desk-buy"') && html.includes('id="desk-claim"') && html.includes('id="desk-send"'),'Buttons missing');
check(config.includes('previewOnly: true') && config.includes('liveTransactionsEnabled: false'),'Transactions must be disabled by default');
check(js.includes('cfg.previewOnly === false && cfg.liveTransactionsEnabled === true'),'Dual safety gate missing');
check(js.includes('selectors.gam') && js.includes('state.tokenAddress = token'),'Token discovery from presale missing');
check(js.includes('TOKEN_PRICE_USD18') && js.includes('MAX_WALLET_USD18'),'On-chain economic terms not checked');
check(js.includes('eth_getCode') && js.includes('eth_chainId'),'On-chain identity & chain checks missing');
check(js.includes('eth_requestAccounts') && js.includes('wallet_switchEthereumChain'),'Wallet integration missing');
check(js.includes('eth_sendTransaction') && js.includes('buyTokens') && js.includes('claim'),'Transaction integration missing');
check(js.includes('quoteUsd18') && js.includes('quoteTokens'), 'On-chain pricing missing');
check(js.includes('desiredChain === 56') && js.includes('pancakeswap.finance/swap'),'Mainnet-only DEX safety missing');
console.log('11 Gambit wallet desk checks passed');
